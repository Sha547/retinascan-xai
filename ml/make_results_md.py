"""Render RESULTS.md from the measured artifacts. Never edit numbers in RESULTS.md by hand.

  python ml/make_results_md.py --artifacts artifacts --out RESULTS.md

Reads results.json (required), abstention_test.csv, and, when present,
degradation.json, serving_check.json, abstention_external.csv. Every number in
the output comes from those files.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

LABELS = ["No DR", "Mild NPDR", "Moderate NPDR", "Severe NPDR", "Proliferative DR"]


def f3(x):
    return "n/a" if x is None or x != x else f"{x:.3f}"


def pct(x):
    return "n/a" if x is None or x != x else f"{100 * x:.1f}%"


def ci(r, k):
    c = r.get("bootstrap_95ci", {}).get(k)
    return f"{c[0]:.3f} to {c[1]:.3f}" if c else ""


def block(r):
    g, ref, cal, ab = r["grading"], r["referable"], r["calibration"], r["abstention"]
    return [
        ("QWK (grades 0 to 4)", f3(g["qwk"]), ci(r, "qwk")),
        ("Accuracy (5-class)", f3(g["accuracy"]), ci(r, "accuracy")),
        ("Referable DR sensitivity", f"{f3(ref['sensitivity'])} ({ref['tp']}/{ref['tp'] + ref['fn']})", ci(r, "sensitivity")),
        ("Referable DR specificity", f"{f3(ref['specificity'])} ({ref['tn']}/{ref['tn'] + ref['fp']})", ci(r, "specificity")),
        ("Referable DR AUC", f3(ref["auc"]), ci(r, "auc")),
        ("Referable PPV / NPV", f"{f3(ref['ppv'])} / {f3(ref['npv'])}", ""),
        ("ECE before then after temperature scaling", f"{f3(cal['ece_before'])} then {f3(cal['ece_after'])}", ""),
        ("NLL before then after temperature scaling", f"{f3(cal['nll_before'])} then {f3(cal['nll_after'])}", ""),
        ("Abstention rate", pct(ab["abstention_rate"]), ""),
        ("Accuracy on graded (non-abstained) cases vs all", f"{f3(ab['accuracy_graded'])} vs {f3(ab['accuracy_overall'])}", ""),
        ("QWK on graded cases vs all", f"{f3(ab['qwk_graded'])} vs {f3(ab['qwk_overall'])}", ""),
    ]


def table(rows, head=("Metric", "Value", "95% bootstrap CI")):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--artifacts", default="artifacts")
    ap.add_argument("--out", default="RESULTS.md")
    a = ap.parse_args()
    A = Path(a.artifacts)
    R = json.loads((A / "results.json").read_text())
    data = json.loads((A / "data_report.json").read_text()) if (A / "data_report.json").exists() else None
    t, v, cal, m = R["test"], R["validation"], R["calibration"], R["model"]

    L = ["# RetinaScan XAI: measured results", "",
         "> Generated by `ml/make_results_md.py` from `artifacts/*.json`/`*.csv`. Do not edit numbers by hand.",
         f"> Source: `results.json` generated {R['generated_at']} (code digest `{R['code_digest']}`).", "",
         "**Research prototype, not clinically validated.** Public datasets are not real primary-health-centre images.", "",
         "## Model and protocol", "",
         f"- Model `{m['version']}`: {m['arch']} (ImageNet-pretrained, fine-tuned), {m['img_size']} px, "
         f"retina crop{' + CLAHE' if m.get('clahe') else ''}; checkpoint from epoch {m['epoch']}, "
         f"chosen by validation QWK ({f3(m['val_qwk'])}).",
         f"- Split: {R['protocol']['split']}.",
         f"- Fitted on validation only: {', '.join(R['protocol']['fitted_on_validation'])}.",
         f"- Test split: {R['protocol']['test_used_for']}. No test-time augmentation.",
         f"- Temperature T = {cal['temperature']:.3f}; referable if P(grade >= 2) >= {cal['referable_threshold']:.3f} "
         f"(chosen for validation sensitivity >= {cal['target_val_sensitivity']}); abstain if max probability < "
         f"{cal['abstain_threshold']:.3f} (chosen for about {pct(cal['target_val_coverage'])} validation coverage).", ""]
    if data:
        d = data["duplicates"]
        L += ["## Data (APTOS 2019, labelled training set only)", "",
              f"- {data['n_used']} images used of {data['n_rows_csv']} rows; "
              f"{len(data['unreadable'])} unreadable, {len(data['missing_file'])} missing.",
              f"- Split sizes: " + ", ".join(f"{k} {v}" for k, v in data["split_sizes"].items()) + ".",
              f"- Near-duplicates (dHash, distance <= {d['dhash_max_distance']}/256): {d['n_groups_with_duplicates']} groups, "
              f"{d['n_images_in_duplicate_groups']} images, kept within a single split; "
              f"{d['n_groups_with_conflicting_labels']} groups have conflicting grades (label noise, kept as is).", ""]

    L += [f"## Held-out test set (n = {t['n']})", "",
          "Class counts: " + ", ".join(f"{k} {n}" for k, n in t["class_counts"].items()) + ".", "",
          table(block(t)), "",
          "Confusion matrix (rows = true grade, columns = predicted grade):", "",
          table([[LABELS[i]] + row for i, row in enumerate(t["grading"]["confusion_matrix"])],
                head=("true \\ pred", *[str(k) for k in range(5)])), ""]

    if (A / "abstention_test.csv").exists():
        df = pd.read_csv(A / "abstention_test.csv")
        L += ["### Abstention trade-off (test; each threshold is a validation quantile)", "",
              table([[pct(r.target_val_coverage), f"{r.threshold_from_val:.3f}", pct(1 - r.n_graded / t["n"]),
                      r.n_graded, f3(r.accuracy_graded), f3(r.qwk_graded)] for r in df.itertuples()],
                    head=("val coverage target", "threshold", "test abstention", "graded", "accuracy graded",
                          "QWK graded")), ""]

    L += [f"## Validation set (n = {v['n']}; used for fitting, so optimistic)", "", table(block(v)), ""]

    ext = R.get("external")
    if ext:
        dr = R["external_drop"]
        L += [f"## External dataset: {ext['split']} (n = {ext['n']})", "",
              "Same model, same validation-fitted temperature and thresholds; nothing refitted.", "",
              table(block(ext)), "",
              "Drop from APTOS test to external (positive = worse on external): "
              f"QWK {dr['qwk']:+.3f}, accuracy {dr['accuracy']:+.3f}, referable AUC {dr['referable_auc']:+.3f}, "
              f"sensitivity {dr['referable_sensitivity']:+.3f}, specificity {dr['referable_specificity']:+.3f}, "
              f"ECE {dr['ece_after']:+.3f} (external minus test).", ""]
    else:
        L += ["## External dataset", "", "_Not evaluated yet._", ""]

    if (A / "degradation.json").exists():
        D = json.loads((A / "degradation.json").read_text())
        gate = D.get("quality_gate_used")
        head = ["condition", "accuracy", "QWK", "ref. sens", "ref. spec", "abstention"] + (
            ["gate rejects", "accuracy if passed"] if gate else [])
        L += ["## Image degradation (test images, synthetic)", "", D["note"] + ".", "",
              table([[r["condition"], f3(r["accuracy"]), f3(r["qwk"]), f3(r["referable_sensitivity"]),
                      f3(r["referable_specificity"]), pct(r["abstention_rate"])]
                     + ([pct(r.get("quality_reject_rate")), f3(r.get("accuracy_on_gate_passed"))] if gate else [])
                     for r in D["rows"]], head=head), ""]
    if (A / "serving_check.json").exists():
        S = json.loads((A / "serving_check.json").read_text())
        L += ["## Serving consistency", "",
              f"- Served probabilities vs evaluation: max abs difference {S['prob_parity']['max_abs_diff']:.4f}, "
              f"argmax agreement {pct(S['prob_parity']['argmax_agreement'])} (n = {S['prob_parity']['n']}).",
              f"- A training image retrieves itself as top similar case: {pct(S['self_retrieval_top1']['rate'])}.",
              f"- Validation/test images in the similar-case index: {S['index_contains_val_or_test']}.", ""]

    L += ["## Limitations (read before quoting any number)", "",
          "- **Image-level split.** APTOS has no patient IDs, so two photos of the same patient (e.g. both eyes) can "
          "fall in different splits. Near-duplicate images are grouped, but this does not remove same-patient leakage; "
          "test numbers may be optimistic.",
          "- **Not real PHC images.** Per the Kaggle data description, APTOS images were gathered from multiple "
          "clinics using a variety of cameras. Images from rural primary health centres may differ and be worse. "
          "See the external and degradation sections.",
          "- **Label noise.** APTOS grades come from single clinicians; conflicting duplicate labels were found (see Data).",
          "- **Weak classes.** Mild and severe NPDR are the least accurate grades (see the confusion matrix). "
          "The referable decision is more reliable than the exact grade.",
          "- **Grad-CAM is coarse.** It shows regions that influenced the grade, at about 32 px resolution. It is "
          "not lesion detection or segmentation.",
          "- **Calibration** is fitted on one validation split of about 550 images; ECE is noisy at this size.",
          "- **Not clinically validated.** No prospective study, no clinician-reviewed pilot, no regulatory review.", ""]
    Path(a.out).write_text("\n".join(L))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
