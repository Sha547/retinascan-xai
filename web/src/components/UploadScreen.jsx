import { useRef, useState } from 'react';
import { SAMPLES } from '../demoModel.js';
import { CheckIcon, ScanIcon, UploadIcon } from './Icons.jsx';

export default function UploadScreen({ scan, onPickFile, onPickSample, onAnalyse, onClear, demo, busy }) {
  const [dragging, setDragging] = useState(false);
  const inputRef = useRef(null);
  const [patientId, setPatientId] = useState('');
  const [eye, setEye] = useState('unknown');
  const [outcome, setOutcome] = useState('graded');

  function handleDrop(e) {
    e.preventDefault();
    setDragging(false);
    const file = e.dataTransfer.files?.[0];
    if (file) onPickFile(file);
  }

  return (
    <div className="screen">
      <div className="section-head">
        <span className="eyebrow">Step 1 · Image acquisition</span>
        <h1>Upload a retinal fundus image</h1>
        <p>
          Drop a fundus photograph captured at the screening camera, or load one of the demo scans below to walk
          through the full pipeline.
        </p>
      </div>

      <div className="upload-grid">
        <div>
          <div
            className={`dropzone ${dragging ? 'dragging' : ''} ${scan ? 'has-image' : ''}`}
            onDragOver={(e) => {
              e.preventDefault();
              setDragging(true);
            }}
            onDragLeave={() => setDragging(false)}
            onDrop={handleDrop}
          >
            <input
              ref={inputRef}
              type="file"
              disabled={busy} accept="image/jpeg,image/png" aria-label="Choose a retinal JPEG or PNG image"
              hidden
              onChange={(e) => {
                const file = e.target.files?.[0];
                if (file) onPickFile(file);
                e.target.value = '';
              }}
            />

            {scan ? (
              <div className="preview">
                <img className="preview-thumb" src={scan.image} alt="Selected retinal scan" />
                <div className="preview-meta">
                  <p className="preview-name">{scan.name}</p>
                  <div className="preview-rows">
                    <div>
                      <span>Source</span>
                      <span>{scan.sampleId ? 'Synthetic sample' : 'Local upload'}</span>
                    </div>
                    <div>
                      <span>Eye / field</span>
                      <span>{scan.caption}</span>
                    </div>
                    <div>
                      <span>Status</span>
                      <span>Ready for analysis</span>
                    </div>
                  </div>
                  <div style={{ display: 'flex', gap: 14, marginTop: 16 }}>
                    <button type="button" className="link-btn" onClick={() => inputRef.current?.click()}>
                      Replace image
                    </button>
                    <button type="button" className="link-btn" onClick={onClear}>
                      Remove
                    </button>
                  </div>
                </div>
              </div>
            ) : (
              <div>
                <div className="dz-icon">
                  <UploadIcon />
                </div>
                <p className="dz-title">Drag and drop a fundus image</p>
                <p className="dz-sub">
                  or{' '}
                  <button type="button" className="link-btn" onClick={() => inputRef.current?.click()}>
                    browse your files
                  </button>
                </p>
                <p className="dz-hint">JPEG or PNG · up to 15 MB</p>
              </div>
            )}
          </div>

          <div className="upload-fields">
            <label>Patient ID (optional)<input value={patientId} onChange={e => setPatientId(e.target.value)} placeholder="Generated by the API if blank" /></label>
            <label>Eye<select value={eye} onChange={e => setEye(e.target.value)}><option value="unknown">Unknown</option><option value="left">Left</option><option value="right">Right</option></select></label>
            {demo && <label>Demo outcome for uploaded files<select value={outcome} onChange={e => setOutcome(e.target.value)}><option value="graded">Graded fixture</option><option value="abstained">Abstained fixture</option><option value="retake">Retake fixture</option></select></label>}
          </div>
          <div className="action-row">
            <button type="button" className="btn btn-primary" disabled={!scan || busy} onClick={() => onAnalyse({ patient_id: patientId, eye, outcome })}>
              <ScanIcon width={17} height={17} />
              Analyse Image
            </button>
            <span className="action-note">
              {busy ? 'Preparing image…' : scan ? 'Runs quality check, then grading and saliency mapping.' : 'Select an image to enable analysis.'}
            </span>
          </div>
        </div>

        <aside className="card samples">
          <h3>Synthetic sample scans</h3>
          <p>{demo ? 'Choose a fixture outcome for the walkthrough.' : 'Illustrations rasterised and uploaded to the API; outcomes are determined by the service.'}</p>
          <div className="sample-list">
            {SAMPLES.map((s, index) => (
              <button
                key={s.id}
                type="button"
                className={`sample ${scan?.sampleId === s.id ? 'selected' : ''}`}
                disabled={busy}
                onClick={() => onPickSample(s)}
              >
                <img src={s.image} alt="" />
                <span>
                  <span className="sample-label">{demo ? s.label : `Synthetic sample ${index + 1}`}</span>
                  <br />
                  <span className="sample-caption">{s.caption}</span>
                </span>
                <span className="sample-check">
                  <CheckIcon width={16} height={16} />
                </span>
              </button>
            ))}
          </div>
          <p className="footnote" style={{ marginTop: 18, textAlign: 'left' }}>
            {demo ? 'Fixture outputs are fake and do not describe the selected image.' : 'Synthetic samples are illustrations, not patient photographs.'}
          </p>
        </aside>
      </div>

    </div>
  );
}
